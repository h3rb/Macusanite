/**
 * Every icon in one list, built once: `{ char, name, section }`. A character
 * listed twice (a chess piece that is also a game piece, say) appears once,
 * under the first section that offers it.
 */
export const ICON_LIBRARY = (() => {
  const seen = new Set();
  const icons = [];
  for (const section of ICON_SECTIONS) {
    for (const [char, name] of section.icons) {
      if (seen.has(char)) continue;
      seen.add(char);
      icons.push({ char, name, section: section.label });
    }
  }
  return icons;
})();

/**
 * Icons matching a search: every term must appear somewhere in the icon's
 * name, its section or the character itself, so "sea ship" narrows to the
 * ship rather than everything maritime. A query that is exactly one
 * character finds that character. No query lists the whole set.
 */
export function searchIcons(query = '') {
  const text = String(query ?? '').trim();
  if (!text) return ICON_LIBRARY;
  if ([...text].length === 1) {
    const exact = ICON_LIBRARY.filter((icon) => icon.char === text);
    if (exact.length) return exact;
  }
  const terms = text.toLowerCase().split(/[^\p{L}\p{N}]+/u).filter(Boolean);
  if (!terms.length) return ICON_LIBRARY;
  return ICON_LIBRARY.filter((icon) => {
    const haystack = `${icon.name} ${icon.section} ${icon.char}`.toLowerCase();
    return terms.every((term) => haystack.includes(term));
  });
}
