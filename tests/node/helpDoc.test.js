/**
 * The manual is generated, so these tests are mostly about *coverage*: every
 * command documented, every parameter described, every section present — and the
 * MCP tool schema of a command derived from the same declaration the document
 * prints. If someone adds a command and forgets the prose, this notices.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import {
  COMMANDS,
  GROUPS,
  commandNames,
  inputSchema,
  isMutating,
  isUndoable,
  toolName,
  prepareArgs,
} from '../../src/lib/catalogue.js';
import {
  buildHelpMarkdown,
  commandPage,
  commandSummary,
  commandReference,
  helpSections,
  helpIndex,
  DOC_TITLE,
  DEFAULT_DOC_SECTIONS,
  FEATURES,
} from '../../src/lib/helpDoc.js';
import { splitManual } from '../../src/lib/helpSearch.js';
import { createVaultApi, ApiError } from '../../src/lib/api.js';

const manual = buildHelpMarkdown();

test('the manual has a section for every feature it claims to document', () => {
  assert.match(manual, new RegExp(`^# ${DOC_TITLE}`));
  const { intro, sections } = splitManual(manual);
  assert.match(intro, /Generated by `npm run docs`/);
  assert.deepEqual(sections.map((section) => section.title), helpSections().map((section) => section.title));
  for (const slug of DEFAULT_DOC_SECTIONS) {
    assert.ok(sections.some((section) => section.slug === slug), `${slug} is missing from the manual`);
  }
  // The generated contents list must point at sections that exist.
  for (const section of helpSections()) {
    assert.ok(manual.includes(`* [${section.title}](#${section.slug})`), `the contents list omits ${section.title}`);
  }
});

test('the manual documents the interfaces this task added', () => {
  // The CLI, its global options, all three MCP transports and the help window.
  for (const phrase of [
    'macusanite vault info',
    'cli/macusanite.mjs',
    'mcp stdio',
    'mcp serve',
    '--port 8765',
    'mcp intake',
    '.request.json',
    'initialize',
    'server/discover',
    '2026-07-28',
    '127.0.0.1',
    'docs/Help.md',
    'help window',
    'Ctrl+Z',
    'ghost',
    'F1',
    'macusanite://manual',
  ]) {
    assert.ok(manual.includes(phrase), `the manual should mention ${phrase}`);
  }
});

test('every command is documented with its arguments, result and examples', () => {
  for (const name of commandNames()) {
    const entry = COMMANDS[name];
    assert.ok(entry.summary && entry.summary.length > 10, `${name} needs a summary`);
    assert.ok(GROUPS.includes(entry.group), `${name} has an unknown group: ${entry.group}`);
    assert.ok(manual.includes(`### \`${name}\``), `${name} is missing from the reference`);
    assert.ok(manual.includes(entry.summary), `${name}'s summary is missing`);

    const page = commandPage(name);
    assert.ok(page, `${name} has no page`);
    assert.ok(page.includes(entry.summary));
    for (const param of entry.params ?? []) {
      assert.match(page, new RegExp(`\\| \`${param.name}\` \\|`), `${name}.${param.name} is not documented`);
      assert.ok(param.description, `${name}.${param.name} needs a description`);
      if (param.values) for (const value of param.values) assert.ok(page.includes(`\`${value}\``));
    }
    if (entry.returns) assert.match(page, /^\*\*Returns\*\* /m);
    for (const example of entry.examples ?? []) {
      assert.ok(page.includes(example), `${name}'s example is not in its page: ${example}`);
      // Examples have to parse: an argument the catalogue does not declare is a
      // documented command line that does not work.
      assert.match(example, /^macusanite /);
    }
    const expected = [
      isMutating(name) ? 'writes to the vault' : 'reads only',
      isUndoable(name) ? 'records an undo step' : null,
      entry.mcp === false ? 'CLI only, not exposed over MCP' : `MCP tool \`${toolName(name)}\``,
    ].filter(Boolean).join(' · ');
    assert.ok(page.includes(expected), `${name}'s kind line said: ${expected}`);

    const summary = commandSummary(name);
    assert.ok(summary.startsWith(entry.summary));
    for (const param of entry.params ?? []) assert.ok(summary.includes(param.name), `${name}'s tool summary omits ${param.name}`);
  }
});

test('the tool schema is the command declaration, not a second copy', () => {
  for (const name of commandNames()) {
    if (COMMANDS[name].mcp === false) continue;
    const schema = inputSchema(name);
    assert.equal(schema.type, 'object');
    assert.deepEqual(Object.keys(schema.properties).sort(), (COMMANDS[name].params ?? []).map((param) => param.name).sort());
    const required = (COMMANDS[name].params ?? []).filter((param) => param.required).map((param) => param.name);
    assert.deepEqual(schema.required ?? [], required);
    for (const param of COMMANDS[name].params ?? []) {
      assert.equal(schema.properties[param.name].description, param.description);
      if (param.values) assert.deepEqual(schema.properties[param.name].enum, param.values);
    }
    // A tool name is what a client sends back, so it must round trip.
    assert.equal(toolName(name), name.replace(/\./g, '_'));
  }
});

test('the command reference is grouped and complete', () => {
  const reference = commandReference();
  for (const group of GROUPS) assert.ok(reference.includes(`### ${group}`), `${group} is missing`);
  assert.equal((reference.match(/^### `[^`]+`$/gm) ?? []).length, commandNames().length);
  assert.equal(Object.keys(helpIndex().commands).length, commandNames().length);
  assert.deepEqual(helpIndex().sections, helpSections());
  // Features come before the reference, which is how both the window and the
  // CLI read it: prose first, then the tables.
  assert.ok(manual.indexOf('## What Macusanite is') < manual.indexOf('## Command reference'));
});

test('arguments are validated against the same declaration the manual prints', () => {
  // A parameter that is not written down cannot be passed — that is the promise
  // the reference makes for every command.
  assert.equal(prepareArgs('vein.read', { path: 'Home.md', bogus: 1 }).ok, false);
  assert.match(prepareArgs('vein.read', {}).error, /missing required argument: path/);
  assert.deepEqual(prepareArgs('vault.settings.set', { no_undo: true }).ok, false);
  const coerced = prepareArgs('search', { query: 'sieve', limit: '5' });
  assert.deepEqual(coerced.args, { query: 'sieve', limit: 5 });
  const enums = prepareArgs('color.set', { kind: 'sky', color: 'red' });
  assert.match(enums.error, /must be one of page, section, link, concept/);
});

test('the api serves the manual, whole and in sections, and can write it down', async () => {
  const api = createVaultApi({});
  const whole = await api.dispatch('docs', {});
  assert.equal(whole.markdown, manual);
  assert.deepEqual(whole.sections, DEFAULT_DOC_SECTIONS);

  const sections = await api.dispatch('docs', { sections: true });
  assert.deepEqual(sections.sections, helpSections());

  const one = await api.dispatch('docs', { section: 'search' });
  assert.match(one.markdown, /^## Search/);
  assert.ok(!one.markdown.includes('## Command reference'));

  await assert.rejects(() => api.dispatch('docs', { section: 'nope' }), ApiError);

  // `--out` needs somewhere to write; without it the api says so instead of
  // pretending to have written the file.
  await assert.rejects(() => api.dispatch('docs', { out: 'Help.md' }), /cannot write files/);

  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'macusanite-docs-'));
  const target = path.join(dir, 'nested', 'Help.md');
  const writing = createVaultApi({
    writeFile: async (file, contents) => {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, contents, 'utf8');
      return { bytes: contents.length };
    },
  });
  const written = await writing.dispatch('docs', { out: target });
  assert.equal(written.out, target);
  assert.equal(fs.readFileSync(target, 'utf8'), manual);
  fs.rmSync(dir, { recursive: true, force: true });

  const help = await api.dispatch('help', {});
  assert.ok(help.commands.includes('vein.write'));
  const page = await api.dispatch('help', { command: 'vein.write' });
  assert.equal(page.markdown, commandPage('vein.write'));
  await assert.rejects(() => api.dispatch('help', { command: 'nope' }), /unknown command/);
});

test('the checked-in manual matches the generator', () => {
  // `docs/Help.md` is a build artefact of `npm run docs`; if it drifts from the
  // source the window, the CLI and GitHub would tell three different stories.
  const target = path.join(process.cwd(), 'docs', 'Help.md');
  assert.ok(fs.existsSync(target), 'docs/Help.md is missing — run `npm run docs`');
  assert.equal(fs.readFileSync(target, 'utf8'), manual, 'docs/Help.md is stale — run `npm run docs`');
});

test('every feature section has prose worth reading', () => {
  for (const feature of FEATURES) {
    assert.ok(feature.body.length > 200, `${feature.slug} is too short to be a section`);
    assert.ok(feature.title && feature.slug);
  }
});
