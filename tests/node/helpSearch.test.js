/**
 * The help window's search: which sections match, and how often.
 *
 * The window itself needs a browser, but everything it decides with is here, so
 * these tests pin the behaviour a reader relies on — a word has to appear, a
 * phrase has to appear whole, and a section that does not match is hidden rather
 * than merely unhighlighted. Where a test needs the "right answer" it computes it
 * from the manual instead of asserting what the prose happens to say.
 */
import test from 'node:test';
import assert from 'node:assert/strict';

import { buildHelpMarkdown, helpSections } from '../../src/lib/helpDoc.js';
import { splitManual, planSearch } from '../../src/lib/helpSearch.js';
import { tokenize } from '../../src/lib/search.js';

const manual = buildHelpMarkdown();
const { intro, sections } = splitManual(manual);
const slugsOf = (plan) => plan.sections.map((section) => section.slug);
const textOf = (section) => `${section.title}\n${section.body}`.toLowerCase();
const countIn = (section, needle) => textOf(section).split(needle).length - 1;

test('the manual splits into its sections, in order, with no contents list', () => {
  assert.match(intro, /^# Macusanite Help/);
  assert.match(intro, /Generated by `npm run docs`/);
  assert.ok(!intro.includes('## '), 'the intro stops at the first section');

  assert.deepEqual(sections.map((section) => section.slug), helpSections().map((section) => section.slug));
  assert.ok(!sections.some((section) => section.title === 'Contents'), 'the contents list is rebuilt by the window');
  for (const section of sections) {
    assert.ok(section.body.trim().length > 0, `${section.slug} is empty`);
    assert.ok(!section.body.startsWith('## '), `${section.slug} kept its heading out of the body`);
  }
});

test('an empty query shows everything and counts nothing', () => {
  const plan = planSearch(sections, '');
  assert.equal(plan.query, '');
  assert.equal(plan.total, 0);
  assert.deepEqual(plan.terms, []);
  assert.deepEqual(slugsOf(plan), sections.map((section) => section.slug));
  assert.equal(plan.sections[0].hits, 0);
});

test('a section matches exactly when every term appears in it', () => {
  for (const query of ['intake', 'vein', 'mcp server', 'ghost link', 'colour']) {
    const plan = planSearch(sections, query);
    const terms = tokenize(query);
    const expected = sections
      .filter((section) => terms.every((term) => textOf(section).includes(term.lower)))
      .map((section) => section.slug);
    assert.deepEqual(slugsOf(plan), expected, `wrong sections for ${JSON.stringify(query)}`);
    for (const match of plan.sections) {
      const section = sections.find((entry) => entry.slug === match.slug);
      assert.equal(match.hits, terms.reduce((sum, term) => sum + countIn(section, term.lower), 0));
    }
    assert.equal(plan.total, plan.sections.reduce((sum, match) => sum + match.hits, 0));
  }
  assert.ok(slugsOf(planSearch(sections, 'intake')).includes('agents'), 'the agents section documents the file intake');
});

test('two words match in any order, and a quoted phrase has to appear whole', () => {
  assert.deepEqual(slugsOf(planSearch(sections, 'link ghost')), slugsOf(planSearch(sections, 'ghost link')));

  // A phrase that never appears as written finds nothing, even though both
  // words are everywhere.
  assert.deepEqual(slugsOf(planSearch(sections, '"ghost the link"')), []);
  assert.ok(planSearch(sections, 'ghost link').total > 0);
});

test('case is irrelevant and a query nothing mentions finds nothing', () => {
  assert.deepEqual(slugsOf(planSearch(sections, 'INTAKE')), slugsOf(planSearch(sections, 'intake')));
  const nothing = planSearch(sections, 'zzzz-not-in-the-manual');
  assert.equal(nothing.total, 0);
  assert.deepEqual(nothing.sections, []);
});

test('the section heading counts as part of the section', () => {
  const keyboard = sections.find((section) => section.slug === 'keyboard');
  // "Keyboard" is the heading: it matches even where the body never says it.
  assert.deepEqual(slugsOf(planSearch(sections, 'Keyboard')), ['keyboard', 'this-manual']);
  assert.ok(!keyboard.body.toLowerCase().includes('keyboard'), 'the word is only in the heading');
});

test('a preview windows the match instead of running away', () => {
  const plan = planSearch(sections, 'the');
  assert.ok(plan.total > 100);
  for (const match of plan.sections) {
    assert.ok(match.preview.length <= 220, `${match.slug}'s preview is too long`);
    assert.match(match.preview.toLowerCase(), /the/);
  }
});
